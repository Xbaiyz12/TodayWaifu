def band_index(luck: int) -> int:
    """幸运值落在第几个档位（0-7）。"""
    for index, (low, high) in enumerate(LUCK_BANDS):
        if low <= luck <= high:
            return index
    return len(LUCK_BANDS) - 1


def pick_luck_text(luck: int) -> tuple[str, str, str, int]:
    """按幸运值取 (评级, 建议, 寄语, 档位下标)。"""
    index = band_index(luck)
    band = LUCK_POOL[f'band{index}']
    selected = random.choice(band)
    return (selected['tier'], selected['hint'], selected['quote'], index)


